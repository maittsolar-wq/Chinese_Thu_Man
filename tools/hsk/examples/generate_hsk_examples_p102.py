"""P5.10.2 -- Pilot Examples Generation (100 records).

Produces the FIRST controlled pilot batch of vocabulary examples. Never
modifies production vocabulary files or app/src. Never overwrites an
existing pilot artifact.

HONESTY NOTE ON DETERMINISM (required by the phase brief): this script
has two genuinely different parts with different determinism guarantees:
  1. RECORD SELECTION is fully deterministic and mechanically
     reproducible -- see select_pilot_ids() below. Rerunning selection
     against the same production data always yields the same 100 IDs in
     the same order.
  2. EXAMPLE CONTENT (the Chinese sentences, pinyin, and Vietnamese
     translations in EXAMPLES_CONTENT) was authored directly by an LLM
     (this assistant) during this phase, the same way every Related
     Words PAIRS/FAMILY_CLIQUES list in this project's tools/hsk/*.py
     scripts was hand-authored data rather than mechanically derived.
     It is embedded here as literal data, not generated by a separate
     reproducible algorithm. A different generation pass (a different
     LLM call, or the same model on a different day) would very likely
     produce different-but-similarly-valid sentences for the same 100
     words. This script does NOT claim example content is deterministic
     -- only that, given this exact embedded content, writing the
     pilot artifact is deterministic and reproducible byte-for-byte.

SELECTION RULE (deterministic, see select_pilot_ids):
  1. Build the full 5400-record HSK1-6 universe.
  2. Classify every record into a risk tier using the same method as
     the P5.10.1 risk audit, recomputed directly (never copy-pasted):
       tier 3 = word (hanzi) also appears elsewhere in HSK1-6 under a
                different pinyin reading (homograph, different reading)
       tier 4 = word+pinyin combination duplicated by another record
                within the SAME HSK level (same-reading duplicate)
       tier 2 = not tier 3/4, but has >1 partOfSpeech tag OR >1 logged
                candidateMeanings entries (ambiguity signal)
       tier 1 = none of the above (lowest risk)
  3. Exclude tier 3 and tier 4 entirely from the pilot candidate pool
     (per the explicit instruction to keep the normal pilot free of
     homograph/critical-duplicate records).
  4. Allocate 100 slots across the 6 HSK levels proportional to each
     level's ELIGIBLE (tier 1+2) record count, using the largest-
     remainder method for exact integer rounding to 100.
  5. Within each level, sort the eligible pool by (tier, id) ascending
     and take the first N per that level's allocation -- i.e. prefer
     tier 1 records first; only reach into tier 2 if a level's tier-1
     pool were smaller than its allocation (empirically, for this
     100-record pilot, every level's tier-1 pool was large enough on
     its own, so the pilot selected is 100% tier 1).

Usage:
    python generate_hsk_examples_p102.py
    python generate_hsk_examples_p102.py --dry-run   (report selection only, write nothing)
"""


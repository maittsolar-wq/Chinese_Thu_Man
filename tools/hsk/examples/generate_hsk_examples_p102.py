def load_json_text(path: Path) -> str:
    with open(path, "r", encoding="utf-8", newline="") as f:
        return f.read()


def fail(message: str) -> None:
    print(f"FAIL: {message}", file=sys.stderr)
    sys.exit(1)


def load_universe() -> dict:
    universe = {}
    for n in range(1, 7):
        path = REPO_ROOT / "data" / "hsk" / f"hsk{n}" / f"hsk{n}_vocabulary_production.json"
        recs = json.loads(load_json_text(path))
        for r in recs:
            universe[r["id"]] = {**r, "_level": n}
    return universe


def get_pos(r: dict) -> list:
    if r.get("partOfSpeech"):
        return r["partOfSpeech"]
    if r.get("cixing"):
        return [r["cixing"]]
    return []


def classify_risk_tiers(universe: dict) -> dict:
    word_pinyin = defaultdict(set)
    for r in universe.values():
        word_pinyin[r["word"]].add(r["pinyin"])
    homograph_words = {w for w, p in word_pinyin.items() if len(p) > 1}

    by_level_word_pinyin = defaultdict(list)
    for r in universe.values():
        by_level_word_pinyin[(r["_level"], r["word"], r["pinyin"])].append(r["id"])
    tier4_ids = {rid for ids in by_level_word_pinyin.values() if len(ids) > 1 for rid in ids}

    tier3_ids = {rid for rid, r in universe.items() if r["word"] in homograph_words} - tier4_ids

    tiers = {}
    for rid, r in universe.items():
        if rid in tier4_ids:
            tiers[rid] = 4
        elif rid in tier3_ids:
            tiers[rid] = 3
        else:
            pos = get_pos(r)
            cm = len(r.get("candidateMeanings") or [])
            tiers[rid] = 2 if (len(pos) > 1 or cm > 1) else 1
    return tiers


def select_pilot_ids(universe: dict, tiers: dict) -> list:
    eligible_by_level = defaultdict(list)
    for rid, r in universe.items():
        if tiers[rid] in (1, 2):
            eligible_by_level[r["_level"]].append(rid)
    for n in range(1, 7):
        eligible_by_level[n].sort()

    eligible_counts = {n: len(eligible_by_level[n]) for n in range(1, 7)}
    total_eligible = sum(eligible_counts.values())

    raw = {n: eligible_counts[n] / total_eligible * TARGET_PILOT_SIZE for n in range(1, 7)}
    alloc = {n: int(raw[n]) for n in range(1, 7)}
    remainder = TARGET_PILOT_SIZE - sum(alloc.values())
    order = sorted(range(1, 7), key=lambda n: -(raw[n] - alloc[n]))
    for i in range(remainder):
        alloc[order[i]] += 1

    selected = []
    for n in range(1, 7):
        pool = sorted(eligible_by_level[n], key=lambda rid: (tiers[rid], rid))
        selected.extend(pool[: alloc[n]])

    return selected, alloc, eligible_counts



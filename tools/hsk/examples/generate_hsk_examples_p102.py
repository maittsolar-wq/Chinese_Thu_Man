# Records selected by select_pilot_ids() but deliberately withheld from
# EXAMPLES_CONTENT because a confident, safe example could not be
# authored -- see module docstring / P5.10.2 report for the reasoning.
PILOT_NEEDS_REVIEW: dict[str, str] = {
    "hsk6_0027": (
        "爆 (bào) is tagged in production as a bound cooking-technique "
        "verb (meaningVi: 'chiên nhanh' / quick-fry), which is an unusual, "
        "narrow, and rarely-standalone sense (爆 is far more commonly seen "
        "in compounds like 爆发/爆炸, which are separate production "
        "records at hsk6_0028/hsk6_0033). A natural standalone sentence risks "
        "either sounding unnatural or accidentally demonstrating the far more "
        "common 'burst/explode' sense instead. Flagged needs_review rather than "
        "guessed, per the explicit generation-safety rule."
    ),
}


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--dry-run", action="store_true", help="Report selection only, write nothing.")
    args = parser.parse_args()

    universe = load_universe()
    tiers = classify_risk_tiers(universe)
    selected_ids, alloc, eligible_counts = select_pilot_ids(universe, tiers)

    if len(selected_ids) != TARGET_PILOT_SIZE:
        fail(f"selection produced {len(selected_ids)} records, expected {TARGET_PILOT_SIZE}")

    level_counts = defaultdict(int)
    for rid in selected_ids:
        level_counts[universe[rid]["_level"]] += 1

    print("=== P5.10.2 pilot selection ===")
    print(f"eligible per level (tier1+2 only): {dict(eligible_counts)}")
    print(f"allocation: {dict(alloc)}")
    print(f"selected: {len(selected_ids)} records")
    print(f"level distribution of selected: {dict(level_counts)}")
    tier_dist = defaultdict(int)
    for rid in selected_ids:
        tier_dist[tiers[rid]] += 1
    print(f"risk tier distribution of selected: {dict(tier_dist)}")

    if args.dry_run:
        print("=== DRY RUN: no files written ===")
        return

    if OUTPUT_PATH.exists():
        fail(f"{OUTPUT_PATH} already exists -- this script refuses to overwrite an existing pilot artifact.")

    missing_content = [rid for rid in selected_ids if rid not in EXAMPLES_CONTENT and rid not in PILOT_NEEDS_REVIEW]
    if missing_content:
        fail(f"selected record(s) have no authored content and are not flagged needs_review: {missing_content}")

    # source production hashes, per level actually touched by this pilot
    source_hashes = {}
    for n in sorted(level_counts.keys()):
        path = REPO_ROOT / "data" / "hsk" / f"hsk{n}" / f"hsk{n}_vocabulary_production.json"
        source_hashes[f"hsk{n}"] = hashlib.sha256(load_json_text(path).encode("utf-8")).hexdigest()

    generated_at = datetime.now(timezone.utc).isoformat()

    records_out = []
    total_examples = 0
    for rid in selected_ids:
        r = universe[rid]
        level = r["_level"]
        if rid in PILOT_NEEDS_REVIEW:
            records_out.append({
                "sourceId": rid,
                "sourceWord": r["word"],
                "hskLevel": level,
                "riskTier": tiers[rid],
                "qaStatus": "needs_review",
                "reviewerStatus": "unreviewed",
                "needsReviewReason": PILOT_NEEDS_REVIEW[rid],
                "examples": [],
            })
            continue
        examples = EXAMPLES_CONTENT[rid]
        total_examples += len(examples)
        records_out.append({
            "sourceId": rid,
            "sourceWord": r["word"],
            "hskLevel": level,
            "riskTier": tiers[rid],
            "qaStatus": "pending",
            "reviewerStatus": "unreviewed",
            "examples": examples,
        })

    artifact = {
        "pilotVersion": PILOT_VERSION,
        "generationBatch": GENERATION_BATCH,
        "generatedAt": generated_at,
        "generationMethod": GENERATION_METHOD,
        "generatorScript": "tools/hsk/examples/generate_hsk_examples_p102.py",
        "selectionRuleSummary": (
            "Deterministic: exclude risk tier 3 (homograph, different reading) "
            "and tier 4 (same-level same-pinyin duplicate); allocate 100 slots "
            "across HSK1-6 proportional to each level's eligible (tier1+2) "
            "count via largest-remainder rounding; within each level take the "
            "lowest-risk-first, id-ascending-sorted eligible records up to that "
            "level's allocation."
        ),
        "sourceProductionHashes": source_hashes,
        "pilotSize": len(records_out),
        "recordsWithExamples": sum(1 for r in records_out if r["examples"]),
        "recordsNeedsReview": sum(1 for r in records_out if r["qaStatus"] == "needs_review"),
        "totalExamples": total_examples,
        "records": records_out,
    }

    output_text = json.dumps(artifact, indent=2, ensure_ascii=False) + "\n"
    OUTPUT_PATH.parent.mkdir(parents=True, exist_ok=True)
    with open(OUTPUT_PATH, "w", encoding="utf-8", newline="") as f:
        f.write(output_text)

    print(f"Wrote {OUTPUT_PATH}")
    print(f"records={len(records_out)} total_examples={total_examples} needs_review={artifact['recordsNeedsReview']}")


if __name__ == "__main__":
    main()
